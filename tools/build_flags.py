"""Bake the Escape Cup flag PNGs into docs/flags.js as tiny inline data URIs.

Poki forbids external requests, and every extra KB costs players, so each flag
is shrunk to 60x40 and embedded. Source: ../escape-cup/assets/flags (public-domain
national flags, fetched from flagcdn.com by that repo).
"""
import base64, io, json, pathlib
from PIL import Image

SRC = pathlib.Path(__file__).resolve().parents[2] / "escape-cup" / "assets" / "flags"
OUT = pathlib.Path(__file__).resolve().parents[1] / "docs" / "flags.js"

flags = {}
for p in sorted(SRC.glob("*.png")):
    im = Image.open(p).convert("RGB").resize((60, 40), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    flags[p.stem] = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()

OUT.write_text("// generated by tools/build_flags.py\nconst FLAG_DATA = " + json.dumps(flags) + ";\n")
print(len(flags), "flags,", OUT.stat().st_size // 1024, "KB")
